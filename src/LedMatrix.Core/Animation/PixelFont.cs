namespace LedMatrix.Core.Animation;

public enum FontChoice
{
    /// <summary>Largest font that fits without scrolling.</summary>
    Auto,
    Regular,
    Tiny,
}

/// <summary>
/// Pixel fonts drawn for this project. Regular is 5x7, Tiny is 3x5. Lowercase maps to uppercase;
/// unknown characters render as '?'.
/// </summary>
public sealed class PixelFont
{
    private readonly Dictionary<char, string[]> _glyphs;

    private PixelFont(string name, int width, int height, Dictionary<char, string[]> glyphs)
    {
        Name = name;
        Width = width;
        Height = height;
        _glyphs = glyphs;
    }

    public string Name { get; }

    public int Width { get; }

    public int Height { get; }

    public static PixelFont Regular { get; } = new("Full size", 5, 7, BuildRegular());

    public static PixelFont Tiny { get; } = new("½ size", 3, 5, BuildTiny());

    public static PixelFont For(FontChoice choice) => choice == FontChoice.Tiny ? Tiny : Regular;

    public bool Supports(char c) => _glyphs.ContainsKey(char.ToUpperInvariant(c));

    /// <summary>True if pixel (x, y) of the glyph is lit.</summary>
    public bool IsLit(char c, int x, int y)
    {
        if (!_glyphs.TryGetValue(char.ToUpperInvariant(c), out var rows))
        {
            rows = _glyphs['?'];
        }

        return rows[y][x] == '#';
    }

